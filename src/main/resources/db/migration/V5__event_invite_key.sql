-- =============================================================================
-- V5 · 비공개 일정에 추측할 수 없는 초대 키를 붙인다
--
-- 왜 필요한가 ------------------------------------------------------------------
-- 「비공개 — 링크로만 참가」를 만들고 목록에서 가렸지만, 주소가 /events/1,
-- /events/2 … 처럼 순서대로였다. 1부터 눌러보면 비공개 일정이 전부 나온다.
-- 목록에서 가린 것이 아무 의미가 없었다.
--
-- 단건 조회를 막는 것으로는 해결되지 않는다. 링크를 받은 사람은 로그인 전에도
-- 내용을 보고 들어올지 정할 수 있어야 하고, 그게 「링크로만 참가」의 뜻이다.
-- 막아야 하는 것은 "주소를 아는 사람"이 아니라 "주소를 찍어보는 사람"이다.
--
-- 그래서 주소 자체를 추측할 수 없게 만든다. id 는 그대로 두고 키를 하나 더 붙인다.
--
--   전   /events/7
--   후   /events/7?key=Kx3f9_aQ2LmP8vTz
--
-- 길이 ------------------------------------------------------------------------
-- 무작위 12바이트를 URL 에 쓸 수 있는 글자로 옮기면 16자가 된다.
-- 경우의 수가 2^96 이라 초당 100만 번씩 찍어봐도 끝나지 않는다.
-- 사람이 외울 일은 없고 복사해서 보내는 값이므로 길이는 문제가 아니다.
--
-- 기존 행 채우기 ----------------------------------------------------------------
-- RANDOM_BYTES 는 MySQL 8 의 암호학적 난수다. RAND() 나 MD5(RAND()) 로 채우면
-- 예측 가능한 값이 들어간다 — 지금 막으려는 바로 그 문제가 된다.
-- base64 의 + / 는 주소에서 뜻이 다르므로 - _ 로 바꾼다.
-- =============================================================================

-- VARCHAR 로 둔다. 자바의 String 은 varchar 로 매핑되고,
-- ddl-auto=validate 가 기동할 때 컬럼 타입을 대조하기 때문이다.
ALTER TABLE event ADD COLUMN invite_key VARCHAR(16) NULL AFTER visibility;

UPDATE event
   SET invite_key = REPLACE(REPLACE(TO_BASE64(RANDOM_BYTES(12)), '+', '-'), '/', '_')
 WHERE invite_key IS NULL;

ALTER TABLE event MODIFY COLUMN invite_key VARCHAR(16) NOT NULL;

-- 고유 제약을 거는 이유는 충돌 방지가 아니다(2^96 중에 겹칠 일은 없다).
-- 코드가 잘못되어 같은 키가 여러 일정에 붙는 일을 DB 가 막아주게 하려는 것이다.
CREATE UNIQUE INDEX ux_event_invite_key ON event (invite_key);
